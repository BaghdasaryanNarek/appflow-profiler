import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import prettier from "prettier";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

function findRepoRoot(startDir) {
  let curr = startDir;
  while (curr !== path.dirname(curr)) {
    if (fs.existsSync(path.join(curr, "packages", "contracts", "schema"))) {
      return curr;
    }
    curr = path.dirname(curr);
  }
  throw new Error("Could not find repository root containing packages/contracts/schema");
}

function stripRefSiblings(obj) {
  if (!obj || typeof obj !== "object") return;
  if (Array.isArray(obj)) {
    for (const item of obj) {
      stripRefSiblings(item);
    }
    return;
  }
  if (obj.$ref) {
    delete obj.description;
    delete obj.title;
  }
  for (const key of Object.keys(obj)) {
    stripRefSiblings(obj[key]);
  }
}

async function main() {
  const repoRoot = findRepoRoot(__dirname);
  const schemaDir = path.join(repoRoot, "packages", "contracts", "schema");
  const targetDir = path.join(repoRoot, "apps", "web", "src", "types");
  const targetFile = path.join(targetDir, "contracts.gen.ts");

  fs.mkdirSync(targetDir, { recursive: true });

  const topologyRaw = fs.readFileSync(path.join(schemaDir, "topology.schema.json"), "utf-8");
  const wsRaw = fs.readFileSync(path.join(schemaDir, "ws-protocol.schema.json"), "utf-8");
  const insightsRaw = fs.readFileSync(path.join(schemaDir, "insights.schema.json"), "utf-8");

  const sTopology = JSON.parse(topologyRaw);
  const sWs = JSON.parse(wsRaw);
  const sInsights = JSON.parse(insightsRaw);

  stripRefSiblings(sTopology);
  stripRefSiblings(sWs);
  stripRefSiblings(sInsights);

  const combined = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: "AppFlowContracts",
    type: "object",
    properties: {
      topology: {
        title: "TopologyContracts",
        type: "object",
        properties: sTopology.properties,
        required: sTopology.required,
      },
      ws: {
        title: "WSContracts",
        type: "object",
        properties: sWs.properties,
        required: sWs.required,
      },
      insights: {
        title: "InsightsContracts",
        type: "object",
        properties: sInsights.properties,
        required: sInsights.required,
      },
    },
    $defs: {
      ...sTopology.$defs,
      ...sWs.$defs,
      ...sInsights.$defs,
    },
  };

  const rawTs = await compile(combined, "AppFlowContracts", {
    bannerComment:
      "/* eslint-disable */\n/**\n * This file was automatically generated by apps/web/scripts/gen-contracts.mjs.\n * DO NOT MODIFY IT BY HAND. Instead, modify the source Pydantic models\n * in apps/api and re-run make contracts.\n */\n",
    unreachableDefinitions: true,
  });

  const prettierConfig = (await prettier.resolveConfig(targetFile)) || {};
  const formattedTs = await prettier.format(rawTs, {
    ...prettierConfig,
    parser: "typescript",
  });

  fs.writeFileSync(targetFile, formattedTs, "utf-8");
  console.log(`Generated and formatted: ${path.relative(repoRoot, targetFile)}`);
}

main().catch((err) => {
  console.error("Failed to generate contracts:", err);
  process.exit(1);
});
