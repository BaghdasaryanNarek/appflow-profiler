"""Optimization Advisor domain models and LLM structured-output schemas (Master Plan §4.4)."""

from datetime import UTC, datetime
from enum import StrEnum
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field

FROZEN_MODEL_CONFIG = ConfigDict(frozen=True, extra="forbid")


class RecommendationCategory(StrEnum):
    """Categorical domain of optimization advice."""

    CAPACITY = "capacity"
    CONNECTION_POOLING = "connection_pooling"
    CACHING = "caching"
    RETRY_POLICY = "retry_policy"
    TOPOLOGY = "topology"
    TIMEOUTS = "timeouts"
    OBSERVABILITY = "observability"


class Bottleneck(BaseModel):
    """Diagnosed architectural bottleneck linked to specific telemetry evidence."""

    model_config = FROZEN_MODEL_CONFIG

    node_id: Annotated[str, Field(description="Impacted entity identifier")]
    title: Annotated[str, Field(description="Concise description of the constraint")]
    severity: Annotated[
        Literal["low", "medium", "high"], Field(description="Operational impact level")
    ]
    evidence: Annotated[
        list[str],
        Field(description="Observable metrics or threshold violations grounding the claim"),
    ]


class Recommendation(BaseModel):
    """Actionable infrastructure or configuration optimization proposal."""

    model_config = FROZEN_MODEL_CONFIG

    id: Annotated[str, Field(description="Deterministic recommendation ID (e.g. rec-pool-orders)")]
    title: Annotated[str, Field(description="Executive recommendation summary")]
    category: Annotated[RecommendationCategory, Field(description="Domain classification")]
    priority: Annotated[
        int, Field(ge=1, le=5, description="1 (Urgent/Critical) to 5 (Informational/Low)")
    ]
    rationale: Annotated[str, Field(description="Technical explanation grounded in observations")]
    expected_impact: Annotated[str, Field(description="Anticipated latency or capacity gains")]
    affected_node_ids: Annotated[
        list[str], Field(description="Topology node IDs directly targeted by this recommendation")
    ]
    effort: Annotated[
        Literal["S", "M", "L"], Field(description="Estimated engineering implementation effort")
    ]


class OptimizationReport(BaseModel):
    """Complete architectural optimization report generated by Gemini or heuristic fallback."""

    model_config = FROZEN_MODEL_CONFIG

    report_id: Annotated[str, Field(description="Unique report execution identifier")]
    source: Annotated[
        Literal["gemini", "heuristic"], Field(description="Intelligence engine generating report")
    ]
    digest_hash: Annotated[
        str, Field(description="SHA-256 fingerprint of the topology digest evaluated")
    ]
    summary: Annotated[
        str, Field(max_length=600, description="High-level executive architectural summary")
    ]
    generated_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
    model: str | None = Field(default=None, description="Cloud LLM model identifier if LLM-backed")
    bottlenecks: list[Bottleneck] = Field(default_factory=list)
    recommendations: list[Recommendation] = Field(default_factory=list)
    caveats: list[str] = Field(
        default_factory=list,
        description="Observability blindspots or data quality qualifications",
    )


class AnalyzeRequest(BaseModel):
    """Request payload for triggering an on-demand architectural review."""

    model_config = FROZEN_MODEL_CONFIG

    scope: str = Field(
        default="global", description="Analysis scope: 'global' or a specific node_id"
    )
    focus: str | None = Field(
        default=None, description="Optional targeted focus area (e.g., latency, pooling)"
    )
